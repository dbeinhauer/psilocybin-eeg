"""
Reusable visualisation functions for wavelet (power & phase) analysis.

These plots reproduce, in script form, the figures generated by the
exploratory notebooks under ``notebooks/03-wavelet-analysis/``.

Every function accepts pre-computed numpy arrays plus a small set of
display parameters and writes one figure to disk via ``save_path``.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Optional

import matplotlib.pyplot as plt
import numpy as np
import seaborn as sns
from matplotlib.figure import Figure

from src.analysis.isc import FREQUENCY_BANDS

_logger = logging.getLogger(__name__)


_BAND_BG_COLORS: dict[str, str] = {
    "delta": "#d4e6f1",
    "theta": "#d5f5e3",
    "alpha": "#fdebd0",
    "beta": "#fadbd8",
    "gamma": "#e8daef",
}


def _save_fig(fig: Figure, save_path: Optional[Path]) -> None:
    if save_path is None:
        return
    save_path = Path(save_path)
    save_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(save_path, dpi=150, bbox_inches="tight")


def _ensure_axes_iterable(axes):
    """Return ``axes`` as a list, even when matplotlib returned a scalar."""
    if hasattr(axes, "__iter__"):
        return list(axes)
    return [axes]


