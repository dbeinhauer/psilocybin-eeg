def compute_itpc(phase_4d: np.ndarray) -> np.ndarray:
    """Inter-trial phase coherence over the subject axis.

    :param phase_4d: ``(n_subjects, n_channels, n_freqs, n_times)`` of wavelet
        phase angles in radians.
    :return: ``(n_channels, n_freqs, n_times)`` ITPC values in ``[0, 1]``.
    """
    if phase_4d.ndim != 4:
        raise ValueError(
            f"phase_4d must be 4D (subjects, channels, freqs, times), "
            f"got shape {phase_4d.shape}"
        )
    return np.abs(np.exp(1j * phase_4d).mean(axis=0))


def plot_phase_distribution(
    phase_4d: np.ndarray,
    *,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """Linear and polar histograms of all wavelet phase values."""
    if phase_4d.ndim != 4:
        raise ValueError(
            f"phase_4d must be 4D (subjects, channels, freqs, times), "
            f"got shape {phase_4d.shape}"
        )
    all_phases = phase_4d.ravel()

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    axes[0].hist(
        all_phases,
        bins=64,
        density=True,
        color="steelblue",
        edgecolor="white",
        alpha=0.8,
    )
    axes[0].axhline(
        1.0 / (2 * np.pi), color="red", linestyle="--", label="Uniform density"
    )
    axes[0].set_xlabel("Phase (rad)")
    axes[0].set_ylabel("Density")
    axes[0].set_title(f"Phase distribution — {label}")
    axes[0].legend()

    ax_polar = fig.add_subplot(122, projection="polar")
    counts, bin_edges = np.histogram(all_phases, bins=64, range=(-np.pi, np.pi))
    centres = 0.5 * (bin_edges[:-1] + bin_edges[1:])
    widths = np.diff(bin_edges)
    ax_polar.bar(
        centres, counts, width=widths, color="steelblue", alpha=0.7, edgecolor="white"
    )
    ax_polar.set_title(f"Polar phase histogram — {label}", pad=15)
    axes[1].set_visible(False)

    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


