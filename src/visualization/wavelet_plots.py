"""
Reusable visualisation functions for wavelet (power & phase) analysis.

These plots reproduce, in script form, the figures generated by the
exploratory notebooks under ``notebooks/03-wavelet-analysis/``.

Every function accepts pre-computed numpy arrays plus a small set of
display parameters and writes one figure to disk via ``save_path``.
"""

