def plot_band_itpc_timecourse(
    itpc_full: np.ndarray,
    freqs: np.ndarray,
    sfreq: float,
    *,
    label: str,
    bands: Optional[dict[str, tuple[float, float]]] = None,
    save_path: Optional[Path] = None,
) -> Figure:
    """Per-band ITPC time course (one panel per band)."""
    if itpc_full.ndim != 3:
        raise ValueError(
            f"itpc_full must be 3D (channels, freqs, times), got shape {itpc_full.shape}"
        )
    bands = bands if bands is not None else FREQUENCY_BANDS
    n_times = itpc_full.shape[2]
    time = np.arange(n_times) / float(sfreq)

    fig, axes = plt.subplots(len(bands), 1, figsize=(14, 3 * len(bands)), sharex=True)
    axes = _ensure_axes_iterable(axes)

    for ax, (band, (lo, hi)) in zip(axes, bands.items()):
        band_mask = (freqs >= lo) & (freqs <= hi)
        if not band_mask.any():
            ax.set_visible(False)
            continue
        band_itpc = itpc_full[:, band_mask, :].mean(axis=1)  # (n_channels, n_times)
        band_itpc_avg = band_itpc.mean(axis=0)
        ax.plot(time, band_itpc_avg, color="darkgreen", linewidth=0.8)
        ax.set_ylabel("ITPC")
        ax.set_title(f"{band} ({lo:.0f}–{hi:.0f} Hz)")
        ax.set_ylim(bottom=0)

    axes[-1].set_xlabel("Time (s)")
    fig.suptitle(f"Per-band ITPC time course — {label}", fontsize=13, y=1.01)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


def compute_phase_band_loo_iscs(
    phase_4d: np.ndarray,
    freqs: np.ndarray,
    bands: Optional[dict[str, tuple[float, float]]] = None,
) -> dict[str, np.ndarray]:
    """Per-band channel-wise LOO-ISC computed on cos(circmean(phase)).

    :param phase_4d: ``(n_subjects, n_channels, n_freqs, n_times)`` phase
        angles in radians.
    :param freqs: Wavelet frequencies (Hz).
    :return: ``{band: mean_loo_isc}`` shape ``(n_channels,)`` per band.
    """
    from src.analysis.isc import compute_loo_isc

    if phase_4d.ndim != 4:
        raise ValueError(
            f"phase_4d must be 4D (subjects, channels, freqs, times), "
            f"got shape {phase_4d.shape}"
        )
    bands = bands if bands is not None else FREQUENCY_BANDS

    out: dict[str, np.ndarray] = {}
    for band, (lo, hi) in bands.items():
        band_mask = (freqs >= lo) & (freqs <= hi)
        if not band_mask.any():
            continue
        band_phase_3d = circmean(
            phase_4d[:, :, band_mask, :], high=np.pi, low=-np.pi, axis=2
        )
        cos_phase_3d = np.cos(band_phase_3d)
        _, mean_loo_isc = compute_loo_isc(cos_phase_3d)
        out[band] = mean_loo_isc
    return out


def plot_itpc_vs_isc(
    itpc_full: np.ndarray,
    band_mean_iscs: dict[str, np.ndarray],
    freqs: np.ndarray,
    *,
    label: str,
    bands: Optional[dict[str, tuple[float, float]]] = None,
    save_path: Optional[Path] = None,
) -> Figure:
    """Side-by-side bar + scatter comparison of ITPC and phase LOO-ISC."""
    if itpc_full.ndim != 3:
        raise ValueError(
            f"itpc_full must be 3D (channels, freqs, times), got shape {itpc_full.shape}"
        )
    bands = bands if bands is not None else FREQUENCY_BANDS

    band_mean_itpc: dict[str, float] = {}
    for band, (lo, hi) in bands.items():
        band_mask = (freqs >= lo) & (freqs <= hi)
        if not band_mask.any():
            continue
        band_mean_itpc[band] = float(itpc_full[:, band_mask, :].mean())

    common = [b for b in bands if b in band_mean_itpc and b in band_mean_iscs]
    itpc_vals = [band_mean_itpc[b] for b in common]
    isc_vals = [band_mean_iscs[b].mean() for b in common]

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    x = np.arange(len(common))
    width = 0.35
    axes[0].bar(x - width / 2, itpc_vals, width, label="ITPC", color="darkgreen")
    axes[0].bar(x + width / 2, isc_vals, width, label="ISC(cos φ)", color="steelblue")
    axes[0].set_xticks(x)
    axes[0].set_xticklabels(common)
    axes[0].set_ylabel("Score")
    axes[0].set_title(f"ITPC vs Phase-ISC — {label}")
    axes[0].legend()

    axes[1].scatter(itpc_vals, isc_vals, s=80, color="purple", zorder=3)
    for i, band in enumerate(common):
        axes[1].annotate(
            band, (itpc_vals[i], isc_vals[i]), fontsize=9, ha="left", va="bottom"
        )
    axes[1].set_xlabel("Mean ITPC")
    axes[1].set_ylabel("Mean LOO-ISC(cos φ)")
    axes[1].set_title(f"ITPC–ISC relationship — {label}")

    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig
