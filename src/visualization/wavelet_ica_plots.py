"""
Reusable visualisation functions for wavelet-ICA / PCA decomposition.

These plots reproduce, in script form, the figures generated by the four
exploratory notebooks under ``notebooks/04-wavelet-ica-analysis/``.

Every public function:
- accepts pre-computed numpy arrays and display parameters,
- writes one figure to disk via an optional ``save_path``,
- does **not** call ``plt.show()`` — the caller decides,
- returns the created :class:`~matplotlib.figure.Figure`.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Optional

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.figure import Figure

_logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _save_fig(fig: Figure, save_path: Optional[Path]) -> None:
    if save_path is None:
        return
    save_path = Path(save_path)
    save_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(save_path, dpi=150, bbox_inches="tight")


def _ensure_axes_iterable(axes):
    """Return *axes* as a flat list even when matplotlib gave a scalar."""
    if hasattr(axes, "__iter__"):
        return list(axes)
    return [axes]


_BAND_COLORS: dict[str, str] = {
    "delta": "#d4e6f1",
    "theta": "#d5f5e3",
    "alpha": "#fdebd0",
    "beta": "#fadbd8",
    "gamma": "#e8daef",
}


