        corr = np.corrcoef(ica_channel_loadings[:, :, i])
        last_im = ax.imshow(corr, cmap="RdBu_r", vmin=-1, vmax=1)
        ax.set_xticks(range(n_subj))
        ax.set_xticklabels([f"S{s + 1}" for s in range(n_subj)], fontsize=7)
        ax.set_yticks(range(n_subj))
        ax.set_yticklabels([f"S{s + 1}" for s in range(n_subj)], fontsize=7)
