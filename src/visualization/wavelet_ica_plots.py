def plot_superbrain_pca_scree(
    explained_variance_ratio: np.ndarray,
    *,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """PCA scree plot (bar) + cumulative variance (line).

    :param explained_variance_ratio: ``(n_pca,)`` variance ratios.
    """
    n = len(explained_variance_ratio)
    cumvar = np.cumsum(explained_variance_ratio)

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    axes[0].bar(range(1, n + 1), explained_variance_ratio, color="steelblue")
    axes[0].set_xlabel("Component")
    axes[0].set_ylabel("Variance explained")
    axes[0].set_title(f"PCA Scree Plot — {label}")

    axes[1].plot(range(1, n + 1), cumvar, "o-", color="steelblue")
    axes[1].axhline(0.9, ls="--", color="gray", label="90 %")
    axes[1].set_xlabel("Number of components")
    axes[1].set_ylabel("Cumulative variance explained")
    axes[1].set_title(f"Cumulative Variance — {label}")
    axes[1].legend()

    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


def plot_superbrain_pca_timecourses(
    scores: np.ndarray,
    sfreq: float,
    *,
    n_show: int = 6,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """PCA component time courses.

    :param scores: ``(T, n_pca)`` PCA scores.
    :param sfreq: Sampling frequency (Hz).
    """
    n_show = min(n_show, scores.shape[1])
    time = np.arange(scores.shape[0]) / sfreq

    fig, axes = plt.subplots(n_show, 1, figsize=(14, 2.5 * n_show), sharex=True)
    axes = _ensure_axes_iterable(axes)
    for i, ax in enumerate(axes):
        ax.plot(time, scores[:, i], lw=0.8, color="steelblue")
        ax.set_ylabel(f"PC {i + 1}")
    axes[-1].set_xlabel("Time (s)")
    fig.suptitle(f"PCA Component Time Courses — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


def plot_superbrain_pca_subject_loadings(
    loadings_4d: np.ndarray,
    *,
    n_show: int = 6,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """Horizontal bar chart of per-subject mean |loading|.

    :param loadings_4d: ``(n_pca, S, C, F)`` reshaped PCA components.
    """
    # subject loadings: mean over channels and freqs
    subj_load = np.abs(loadings_4d).mean(axis=(2, 3))  # (K, S)
    n_show = min(n_show, subj_load.shape[0])
    n_subj = subj_load.shape[1]

    fig, axes = plt.subplots(1, n_show, figsize=(3 * n_show, 4), sharey=True)
    axes = _ensure_axes_iterable(axes)
    for i, ax in enumerate(axes):
        ax.barh(range(n_subj), subj_load[i], color="steelblue")
        ax.set_xlabel("|loading|")
        ax.set_title(f"PC {i + 1}")
    axes[0].set_yticks(range(n_subj))
    axes[0].set_yticklabels([f"S{s + 1}" for s in range(n_subj)])
    axes[0].set_ylabel("Subject")
    fig.suptitle(f"Subject Loadings — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


def plot_superbrain_pca_channel_topomap(
    loadings_4d: np.ndarray,
    info,
    *,
    n_show: int = 6,
    label: str,
    save_path: Optional[Path] = None,
) -> Optional[Figure]:
    """Scalp topomaps of PCA channel loadings (mean |loading| over S, F).

    :param loadings_4d: ``(n_pca, S, C, F)``.
    :param info: MNE Info object.
    """
    if info is None:
        _logger.warning("[%s] No MNE Info; skipping topomap.", label)
        return None

    import mne
    from mne.viz import plot_topomap

    eeg_info = mne.pick_info(info, mne.pick_types(info, eeg=True))
    ch_load = np.abs(loadings_4d).mean(axis=(1, 3))  # (K, C)
    n_show = min(n_show, ch_load.shape[0])

    fig, axes = plt.subplots(1, n_show, figsize=(3.5 * n_show, 4))
    axes = _ensure_axes_iterable(axes)
    last_im = None
    for i, ax in enumerate(axes):
        vals = ch_load[i]
        if vals.shape[0] < len(eeg_info["ch_names"]):
            topo_info = mne.pick_info(eeg_info, list(range(vals.shape[0])))
        else:
            topo_info = eeg_info
        vlim = np.percentile(vals, 99)
        last_im, _ = plot_topomap(
            vals, topo_info, axes=ax, show=False, cmap="RdBu_r", vlim=(0, vlim)
        )
        ax.set_title(f"PC {i + 1}")
    fig.suptitle(f"Channel Loadings (topomap) — {label}", fontsize=12)
    if last_im is not None:
        fig.colorbar(last_im, ax=axes[-1], label="mean |loading|")
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


def plot_superbrain_pca_freq_loadings(
    loadings_4d: np.ndarray,
    freqs: np.ndarray,
    *,
    bands: Optional[dict[str, tuple[float, float]]] = None,
    n_show: int = 6,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """Per-component frequency loading curves with band shading.

    :param loadings_4d: ``(n_pca, S, C, F)``.
    :param freqs: Morlet frequencies (Hz).
    """
    freq_load = np.abs(loadings_4d).mean(axis=(1, 2))  # (K, F)
    n_show = min(n_show, freq_load.shape[0])

    fig, axes = plt.subplots(n_show, 1, figsize=(10, 2.5 * n_show), sharex=True)
    axes = _ensure_axes_iterable(axes)
    for i, ax in enumerate(axes):
        ax.plot(freqs, freq_load[i], color="steelblue", lw=1.5)
        ax.set_ylabel("|loading|")
        ax.set_title(f"PC {i + 1}")
        if bands is not None:
            for band, (lo, hi) in bands.items():
                ax.axvspan(lo, hi, alpha=0.2, color=_BAND_COLORS.get(band, "grey"))
    axes[-1].set_xlabel("Frequency (Hz)")
    fig.suptitle(f"Frequency Loadings — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


def plot_superbrain_pca_spectrograms(
    scores: np.ndarray,
    sfreq: float,
    freqs_max: float,
    *,
    n_show: int = 4,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """STFT spectrograms of PCA component time courses.

    :param scores: ``(T, n_pca)``.
    :param sfreq: Sampling frequency (Hz).
    :param freqs_max: Maximum frequency to display (Hz).
    """
    from scipy.signal import spectrogram as sp_spectrogram

    n_show = min(n_show, scores.shape[1])
    nperseg = int(sfreq * 2)
    noverlap = int(sfreq)

    fig, axes = plt.subplots(n_show, 1, figsize=(14, 3 * n_show), sharex=True)
    axes = _ensure_axes_iterable(axes)
    for i, ax in enumerate(axes):
        f, t, Sxx = sp_spectrogram(
            scores[:, i], fs=sfreq, nperseg=nperseg, noverlap=noverlap
        )
        mask = f <= freqs_max
        Sxx_db = 10 * np.log10(Sxx[mask] + 1e-12)
        ax.pcolormesh(t, f[mask], Sxx_db, cmap="inferno", shading="auto")
        ax.set_ylabel("Freq (Hz)")
        ax.set_title(f"PC {i + 1} spectrogram")
    axes[-1].set_xlabel("Time (s)")
    fig.suptitle(f"Component Spectrograms — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


