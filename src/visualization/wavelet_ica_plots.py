def plot_temporal_ica_per_subject_topomaps(
    ica_scores_3d: np.ndarray,
    info,
    *,
    n_show_comp: int = 3,
    label: str,
    save_path: Optional[Path] = None,
) -> Optional[Figure]:
    """Per-subject topomaps for top ICA components.

    :param ica_scores_3d: ``(S, C, n_ica)``.
    :param info: MNE Info.
    """
    if info is None:
        _logger.warning("[%s] No MNE Info; skipping topomap.", label)
        return None

    import mne
    from mne.viz import plot_topomap

    eeg_info = mne.pick_info(info, mne.pick_types(info, eeg=True))
    n_subj, n_ch, n_ica = ica_scores_3d.shape
    n_show_comp = min(n_show_comp, n_ica)

    fig, axes = plt.subplots(
        n_show_comp, n_subj, figsize=(3 * n_subj, 3.5 * n_show_comp), squeeze=False
    )

    for k in range(n_show_comp):
        for s in range(n_subj):
            ax = axes[k, s]
            vals = ica_scores_3d[s, :, k]
            if vals.shape[0] < len(eeg_info["ch_names"]):
                topo_info = mne.pick_info(eeg_info, list(range(vals.shape[0])))
            else:
                topo_info = eeg_info
            plot_topomap(vals, topo_info, axes=ax, show=False, cmap="RdBu_r")
            if k == 0:
                ax.set_title(f"S{s + 1}", fontsize=9)
        axes[k, 0].set_ylabel(f"IC {k + 1}", rotation=90, labelpad=40)
    fig.suptitle(f"Per-Subject ICA Channel Loadings — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


