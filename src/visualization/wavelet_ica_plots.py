def plot_superbrain_cross_component_correlation(
    pca_scores: np.ndarray,
    ica_sources: np.ndarray,
    *,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """Cross-component correlation matrices for PCA and ICA.

    :param pca_scores: ``(T, n_pca)``.
    :param ica_sources: ``(T, n_ica)``.
    """
    pca_corr = np.corrcoef(pca_scores.T)
    ica_corr = np.corrcoef(ica_sources.T)

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    for ax, corr, title in [
        (axes[0], pca_corr, "PCA score correlations"),
        (axes[1], ica_corr, "ICA score correlations"),
    ]:
        im = ax.imshow(corr, cmap="RdBu_r", vmin=-1, vmax=1)
        ax.set_xlabel("Component")
        ax.set_ylabel("Component")
        ax.set_title(title)
        fig.colorbar(im, ax=ax, label="Pearson r")
    fig.suptitle(f"Cross-Component Correlations — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


