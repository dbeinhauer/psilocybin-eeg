def plot_intersubject_pca_channel_freq_maps(
    components_2d: np.ndarray,
    freqs: np.ndarray,
    *,
    n_show: int = 6,
    label: str,
    save_path: Optional[Path] = None,
) -> Figure:
    """Spatial-spectral component maps (channel × frequency heatmaps).

    :param components_2d: ``(n_pca, C, F)`` PCA components reshaped.
    :param freqs: Morlet frequencies (Hz).
    """
    n_show = min(n_show, components_2d.shape[0])
    n_cols = min(3, n_show)
    n_rows = int(np.ceil(n_show / n_cols))

    fig, axes = plt.subplots(n_rows, n_cols, figsize=(5 * n_cols, 4 * n_rows))
    flat = np.array(axes).flatten() if n_show > 1 else [axes]
    for i in range(n_show):
        ax = flat[i]
        im = ax.imshow(
            components_2d[i],
            aspect="auto",
            origin="lower",
            extent=[freqs[0], freqs[-1], 0, components_2d.shape[1]],
            cmap="RdBu_r",
        )
        ax.set_xlabel("Frequency (Hz)")
        ax.set_ylabel("Channel index")
        ax.set_title(f"PC {i + 1}")
        fig.colorbar(im, ax=ax)
    for i in range(n_show, len(flat)):
        flat[i].set_visible(False)
    fig.suptitle(f"Spatial-Spectral Component Maps — {label}", fontsize=13)
    fig.tight_layout()
    _save_fig(fig, save_path)
    plt.close(fig)
    return fig


